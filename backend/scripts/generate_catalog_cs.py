#!/usr/bin/env python3
import json
import uuid
import re

from seed_100_products import CATEGORIES, IMAGES_POOL, RAW_PRODUCTS

def make_slug(name):
    s = name.lower()
    s = re.sub(r'[^a-z0-9]+', '-', s)
    return s.strip('-')

lines = []
lines.append("// <auto-generated />")
lines.append("using PrismCommerce.Domain.Entities;")
lines.append("")
lines.append("namespace PrismCommerce.Infrastructure.Data;")
lines.append("")
lines.append("public static class CatalogSeedData")
lines.append("{")
lines.append("    public static List<Product> GetProducts(Dictionary<string, Category> categoriesMap)")
lines.append("    {")
lines.append("        var list = new List<Product>();")
lines.append("")

for idx, (name, cat_slug, desc, base_price, variants) in enumerate(RAW_PRODUCTS):
    slug = make_slug(name)
    escaped_name = name.replace('"', '\\"')
    escaped_desc = desc.replace('"', '\\"')
    img_key = "phones" if cat_slug == "phones-tablets" else ("gaming" if cat_slug == "gaming-vr" else cat_slug)
    images = IMAGES_POOL.get(img_key, IMAGES_POOL["accessories"])
    img1 = images[idx % len(images)]
    img2 = images[(idx + 1) % len(images)]
    
    lines.append(f"        if (categoriesMap.TryGetValue(\"{cat_slug}\", out var cat{idx}))")
    lines.append("        {")
    lines.append(f"            var p = new Product(cat{idx}.Id, \"{escaped_name}\", \"{slug}\", \"{escaped_desc}\", {base_price:0.2f}m, true, new List<string> {{ \"{img1}\", \"{img2}\" }});")
    
    for v_idx, (color, size, price_adj, stock) in enumerate(variants):
        sku = f"{re.sub(r'[^A-Z0-9]', '', name.upper())[:6]}-{idx+1:03d}-{v_idx+1}"
        v_title = f"{name} - {color}" if color else name
        v_title_escaped = v_title.replace('"', '\\"')
        color_str = f"\"{color}\"" if color else "null"
        size_str = f"\"{size}\"" if size else "null"
        lines.append(f"            var v{idx}_{v_idx} = new ProductVariant(p.Id, \"{sku}\", \"{v_title_escaped}\", {color_str}, {size_str}, {price_adj:0.2f}m);")
        lines.append(f"            v{idx}_{v_idx}.Inventory = new InventoryRecord(v{idx}_{v_idx}.Id, {stock});")
        lines.append(f"            p.Variants.Add(v{idx}_{v_idx});")
    lines.append("            list.Add(p);")
    lines.append("        }")
    lines.append("")

lines.append("        return list;")
lines.append("    }")
lines.append("}")

with open("/Users/pasindugayashan/Documents/Apps/prismcommerce-fullstack/backend/PrismCommerce.Infrastructure/Data/CatalogSeedData.cs", "w") as f:
    f.write("\n".join(lines))

print("CatalogSeedData.cs successfully created!")
